#!/bin/bash
# Remove the parts of site-packages that the server never imports.
#
# The list below is the complement of the runtime import closure, measured by
# calling camoufox.utils.launch_options() across the full option surface and
# reading sys.modules. To re-derive it after bumping CAMOUFOX_VERSION:
#
#   docker build --target builder -t camoufox:builder .
#   docker run --rm -e PYTHONPATH=/opt/venv/lib/python3.11/site-packages \
#       -e XDG_CACHE_HOME=/opt/cache camoufox:builder python3 -c '
#   import sys, glob, os
#   from camoufox.utils import launch_options
#   launch_options(headless=True, os=["windows","macos","linux"], humanize=True)
#   sp = "/opt/venv/lib/python3.11/site-packages/"
#   used = {m.__file__[len(sp):].split("/")[0] for m in list(sys.modules.values())
#           if getattr(m, "__file__", "") and m.__file__.startswith(sp)}
#   print(sorted({p.split("/")[-1] for p in glob.glob(sp+"*") if os.path.isdir(p)} - used))'
#
# Anything removed by mistake surfaces as an ImportError the moment the server
# starts, so a wrong entry here fails loudly rather than silently.
set -euo pipefail

SITE_PACKAGES=${1:?usage: prune-site-packages.sh <site-packages-dir>}

# Interactive CLI machinery. `camoufox fetch` and the version manager use these
# during the build; the server never does.
CLI_ONLY=(blessed editor inquirer jinxed readchar runs wcwidth xmod)

# Rich's optional renderers. Camoufox imports rich to print leak warnings, but
# never asks it to highlight source or render markdown.
RICH_EXTRAS=(markdown_it mdurl pygments)

# Transitive dependencies that nothing on the launch path touches. geoip2 and
# maxminddb look equally unused, but only because they are imported lazily when
# geoip is enabled -- they must stay.
UNUSED=(aiohappyeyeballs aiohttp aiosignal attr attrs frozenlist lxml multidict propcache yarl)

before=$(du -sm "$SITE_PACKAGES" | cut -f1)
for package in "${CLI_ONLY[@]}" "${RICH_EXTRAS[@]}" "${UNUSED[@]}"; do
    rm -rf "${SITE_PACKAGES:?}/$package"
done
after=$(du -sm "$SITE_PACKAGES" | cut -f1)

echo "prune-site-packages: ${before} MB -> ${after} MB" >&2
